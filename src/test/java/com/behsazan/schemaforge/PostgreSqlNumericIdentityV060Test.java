package com.behsazan.schemaforge;

import com.behsazan.schemaforge.application.DatabasePlatform;
import com.behsazan.schemaforge.dialect.SequenceReferenceNormalizer;
import com.behsazan.schemaforge.dialect.postgresql.PostgreSqlDialect;
import com.behsazan.schemaforge.domain.model.Column;
import com.behsazan.schemaforge.domain.model.DatabaseSchema;
import com.behsazan.schemaforge.domain.model.Table;
import com.behsazan.schemaforge.domain.valueobject.DataType;
import com.behsazan.schemaforge.domain.valueobject.DefaultValue;
import com.behsazan.schemaforge.domain.valueobject.Description;
import com.behsazan.schemaforge.domain.valueobject.Identifier;
import com.behsazan.schemaforge.generation.DdlGenerator;
import com.behsazan.schemaforge.migration.ColumnChangeKind;
import com.behsazan.schemaforge.migration.MigrationRenderOptions;
import com.behsazan.schemaforge.migration.MigrationSqlRenderer;
import com.behsazan.schemaforge.migration.SchemaDiffEngine;
import org.junit.jupiter.api.Test;

import static org.junit.jupiter.api.Assertions.*;

/** Oracle/PG sequence-reference equivalence and fail-closed migration for PG NUMERIC IDENTITY. */
class PostgreSqlNumericIdentityV060Test {
    private static Column numericIdentity() {
        return new Column(Identifier.of("ID"), DataType.numeric("NUMBER", 19, 0), false,
                null, Description.empty(), true, 1);
    }

    @Test
    void comparesLivePostgreSqlRegclassNextvalToCanonicalNumericIdentity() {
        Column liveId = new Column(Identifier.of("ID"), DataType.numeric("NUMBER", 19, 0), false,
                new DefaultValue("nextval('app.seq_v060_ids'::regclass)"),
                Description.empty(), false, 1);
        Table live = Table.builder("APP", "V060_IDS").addColumn(liveId).build();
        Table desired = Table.builder("APP", "V060_IDS").addColumn(numericIdentity()).build();
        var changes = new SchemaDiffEngine().diff(DatabasePlatform.POSTGRESQL, live, desired).columnChanges();
        assertFalse(changes.stream().anyMatch(c -> c.kind() == ColumnChangeKind.ALTER_IDENTITY),
                "matching PostgreSQL sequence default should be recognized as logical identity");
        assertFalse(changes.stream().anyMatch(c -> c.kind() == ColumnChangeKind.ALTER_DEFAULT),
                "sequence-backed logical identity must not generate an ALTER DEFAULT");
        assertEquals("APP.SEQ_V060_IDS.NEXTVAL", SequenceReferenceNormalizer.normalize(
                "nextval('app.seq_v060_ids'::regclass)"));
        assertEquals("APP.SEQ_V060_IDS.NEXTVAL", SequenceReferenceNormalizer.normalize(
                "APP.SEQ_V060_IDS.NEXTVAL"));
    }

    @Test
    void blocksIncompleteSequenceBackedIdentityAddColumnMigration() {
        Table live = Table.builder("APP", "V060_IDS")
                .addColumn(Column.required("OTHER_ID", DataType.numeric("NUMBER", 10, 0)))
                .build();
        Table desired = Table.builder("APP", "V060_IDS")
                .addColumn(Column.required("OTHER_ID", DataType.numeric("NUMBER", 10, 0)))
                .addColumn(numericIdentity())
                .build();
        var plan = new SchemaDiffEngine().diff(DatabasePlatform.POSTGRESQL, live, desired);
        String sql = new MigrationSqlRenderer().render(plan, MigrationRenderOptions.safeDefaults());
        assertTrue(sql.contains("BLOCKED: sequence-backed identity ADD COLUMN"));
        assertFalse(sql.contains("ALTER TABLE app.v060_ids ADD COLUMN id"),
                "an incomplete PG numeric identity migration must never be runnable");
        assertFalse(sql.contains("NUMERIC(19,0) GENERATED"));
    }

    @Test
    void keepsNativePostgreSqlIntegerIdentity() {
        Column id = new Column(Identifier.of("ID"), DataType.simple("INTEGER"), false,
                null, Description.empty(), true, 1);
        Table table = Table.builder("APP", "NATIVE_IDS").addColumn(id).build();
        String sql = new DdlGenerator(new PostgreSqlDialect()).generate(
                DatabaseSchema.builder("APP").addTable(table).build());
        assertTrue(sql.contains("INTEGER GENERATED BY DEFAULT AS IDENTITY"));
        assertFalse(sql.contains("CREATE SEQUENCE"));
    }
}
