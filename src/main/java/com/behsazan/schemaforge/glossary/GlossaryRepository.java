package com.behsazan.schemaforge.glossary;

import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.dao.DuplicateKeyException;
import org.springframework.jdbc.core.RowMapper;

import javax.sql.DataSource;
import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.ResultSet;
import java.sql.SQLException;
import java.util.ArrayList;
import java.util.Comparator;
import java.util.HashSet;
import java.util.Locale;
import java.util.List;
import java.util.Objects;
import java.util.Optional;
import java.util.Set;

/** Dedicated H2 glossary database. It never shares target-DBMS metadata connections. */
public final class GlossaryRepository {
    private static final String COLUMNS = "id, kind, term_key, english, persian, module, status, source, created_at, updated_at";
    private static final RowMapper<GlossaryTerm> MAPPER = (rs, rowNum) -> new GlossaryTerm(
            rs.getLong("id"), GlossaryTermKind.valueOf(rs.getString("kind")),
            rs.getString("term_key"), rs.getString("english"), rs.getString("persian"),
            rs.getString("module"), GlossaryTermStatus.valueOf(rs.getString("status")),
            rs.getString("source"), rs.getString("created_at"), rs.getString("updated_at"));

    // Old ATOMIC rows are unambiguously sourced from Atomic Terms; old PHRASE rows
    // are ambiguous and are excluded until matched again by an Atomic-only import.
    private static final String ACTIVE_SCOPE =
            " AND (kind='ATOMIC' OR source<>'ECOBANK_XLSX')";

    private final JdbcTemplate jdbc;
    private final DataSource dataSource;

    public GlossaryRepository(DataSource dataSource) {
        this.dataSource = Objects.requireNonNull(dataSource);
        this.jdbc = new JdbcTemplate(dataSource);
        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS glossary_term (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    kind VARCHAR(12) NOT NULL,
                    term_key VARCHAR(256) NOT NULL,
                    english VARCHAR(512) NOT NULL,
                    persian CLOB,
                    module CLOB,
                    status VARCHAR(12) NOT NULL,
                    source VARCHAR(60) NOT NULL,
                    is_deleted BOOLEAN NOT NULL DEFAULT FALSE,
                    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    updated_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    CONSTRAINT uq_glossary_kind_key UNIQUE (kind, term_key)
                )
                """);
        jdbc.execute("CREATE INDEX IF NOT EXISTS ix_glossary_status ON glossary_term (status, is_deleted)");
    }

    public Optional<GlossaryTerm> get(long id) {
        List<GlossaryTerm> found = jdbc.query(
                "SELECT " + COLUMNS + " FROM glossary_term WHERE id=? AND is_deleted=FALSE", MAPPER, id);
        return found.stream().findFirst();
    }

    /**
     * Searches the small glossary against fully mapped domain values.
     *
     * The same GlossaryTerm projection is used by unfiltered listings and by
     * English/Persian text queries. This avoids applying search predicates to
     * raw JDBC column reads independently from the public response mapping.
     * A single cursor is read for each invocation; no separate SQL COUNT or
     * database pagination query is involved.
     */
    public GlossaryPage search(String query, GlossaryTermKind kind, GlossaryTermStatus status, int page, int size) {
        if (page < 0 || size < 1 || size > 1000 || page > Integer.MAX_VALUE / Math.max(size, 1)) {
            throw new IllegalArgumentException("page must be >= 0 and size must be between 1 and 1000");
        }
        String needle = query == null || query.isBlank()
                ? null : query.strip().toUpperCase(Locale.ROOT);
        List<GlossaryTerm> visible = new ArrayList<>();
        try (Connection connection = dataSource.getConnection();
             PreparedStatement statement = connection.prepareStatement(
                     "SELECT " + COLUMNS + ", is_deleted FROM glossary_term");
             ResultSet rows = statement.executeQuery()) {
            int resultRow = 0;
            while (rows.next()) {
                if (rows.getBoolean("is_deleted")) continue;
                // Old PHRASE records sourced from the non-authoritative sheet
                // are excluded before the more expensive domain mapping.
                if ("PHRASE".equals(rows.getString("kind"))
                        && "ECOBANK_XLSX".equals(rows.getString("source"))) continue;
                visible.add(MAPPER.mapRow(rows, resultRow++));
            }
        } catch (SQLException exception) {
            throw new IllegalStateException("Unable to retrieve glossary search results", exception);
        }
        List<GlossaryTerm> matches = new ArrayList<>();
        for (GlossaryTerm term : visible) {
            if (kind != null && term.kind() != kind) continue;
            if (status != null && term.status() != status) continue;
            if (needle != null && !containsIgnoreCase(term.key(), needle)
                    && !containsIgnoreCase(term.english(), needle)
                    && !containsIgnoreCase(term.persian(), needle)) continue;
            matches.add(term);
        }
        matches.sort(Comparator.comparing(GlossaryTerm::key)
                .thenComparing(term -> term.kind().name()));
        long total = matches.size();
        int offset = Math.multiplyExact(page, size);
        List<GlossaryTerm> items = offset >= matches.size()
                ? List.of()
                : List.copyOf(matches.subList(offset, (int) Math.min((long) offset + size, matches.size())));
        return new GlossaryPage(items, page, size, total);
    }

    private static boolean containsIgnoreCase(String text, String uppercaseNeedle) {
        return text != null && text.toUpperCase(Locale.ROOT).contains(uppercaseNeedle);
    }

    public GlossaryTerm create(GlossaryTermRequest request) {
        CanonicalInput input = requireInput(request);
        // Recreating a soft-deleted entry restores it rather than conflicting with the unique key.
        int restored = jdbc.update("""
                UPDATE glossary_term SET english=?, persian=?, module=?, status=?,
                    source='MANUAL', is_deleted=FALSE, updated_at=CURRENT_TIMESTAMP
                WHERE kind=? AND term_key=? AND is_deleted=TRUE
                """, input.english(), input.persian(), input.module(), input.status().name(),
                input.kind().name(), input.key());
        if (restored == 1) return getByKey(input.kind(), input.key()).orElseThrow();
        try {
            jdbc.update("""
                    INSERT INTO glossary_term (kind, term_key, english, persian, module, status, source)
                    VALUES (?, ?, ?, ?, ?, ?, 'MANUAL')
                    """, input.kind().name(), input.key(), input.english(), input.persian(),
                    input.module(), input.status().name());
        } catch (DuplicateKeyException exception) {
            throw new GlossaryConflictException("Glossary term already exists for kind/key", exception);
        }
        return getByKey(input.kind(), input.key()).orElseThrow();
    }

    public Optional<GlossaryTerm> update(long id, GlossaryTermRequest request) {
        CanonicalInput input = requireInput(request);
        int affected;
        try {
            affected = jdbc.update("""
                    UPDATE glossary_term
                    SET kind=?, term_key=?, english=?, persian=?, module=?, status=?, updated_at=CURRENT_TIMESTAMP
                    WHERE id=? AND is_deleted=FALSE
                    """, input.kind().name(), input.key(), input.english(), input.persian(),
                    input.module(), input.status().name(), id);
        } catch (DuplicateKeyException exception) {
            throw new GlossaryConflictException("Glossary term already exists for kind/key", exception);
        }
        return affected == 0 ? Optional.empty() : get(id);
    }

    public boolean delete(long id) {
        return jdbc.update("UPDATE glossary_term SET is_deleted=TRUE, updated_at=CURRENT_TIMESTAMP "
                + "WHERE id=? AND is_deleted=FALSE", id) == 1;
    }

    public Optional<GlossaryTerm> getByKey(GlossaryTermKind kind, String key) {
        List<GlossaryTerm> found = jdbc.query("SELECT " + COLUMNS
                + " FROM glossary_term WHERE kind=? AND term_key=? AND is_deleted=FALSE",
                MAPPER, kind.name(), key);
        return found.stream().findFirst();
    }

    /** Explicit steward action: bulk-approve only after review, optionally scoped to a kind. */
    public int changeStatus(GlossaryTermKind kind, GlossaryTermStatus from, GlossaryTermStatus to) {
        if (from == null || to == null || from == to)
            throw new IllegalArgumentException("Distinct from/to statuses are required");
        if (kind == null) {
            return jdbc.update("UPDATE glossary_term SET status=?, updated_at=CURRENT_TIMESTAMP "
                    + "WHERE status=? AND is_deleted=FALSE" + ACTIVE_SCOPE, to.name(), from.name());
        }
        return jdbc.update("UPDATE glossary_term SET status=?, updated_at=CURRENT_TIMESTAMP "
                + "WHERE kind=? AND status=? AND is_deleted=FALSE" + ACTIVE_SCOPE,
                to.name(), kind.name(), from.name());
    }

    /** One status-aware snapshot so candidates are never mislabeled as newly discovered terms. */
    public GlossaryLexicon approvedLexicon() {
        Set<String> atomic = new HashSet<>();
        Set<String> phrases = new HashSet<>();
        Set<String> candidatesAtomic = new HashSet<>();
        Set<String> candidatesPhrases = new HashSet<>();
        Set<String> rejectedAtomic = new HashSet<>();
        Set<String> rejectedPhrases = new HashSet<>();
        jdbc.query("SELECT kind, term_key, status FROM glossary_term WHERE is_deleted=FALSE"
                + ACTIVE_SCOPE, rs -> {
            String kind = rs.getString(1);
            String key = rs.getString(2);
            switch (rs.getString(3)) {
                case "APPROVED" -> { if ("ATOMIC".equals(kind)) atomic.add(key); else phrases.add(key); }
                case "CANDIDATE" -> { if ("ATOMIC".equals(kind)) candidatesAtomic.add(key);
                                      else candidatesPhrases.add(key); }
                case "REJECTED" -> { if ("ATOMIC".equals(kind)) rejectedAtomic.add(key);
                                     else rejectedPhrases.add(key); }
                default -> throw new IllegalStateException("Invalid glossary status");
            }
        });
        return new GlossaryLexicon(atomic, phrases, candidatesAtomic, candidatesPhrases,
                rejectedAtomic, rejectedPhrases);
    }

    /**
     * Atomically imports the authoritative Atomic Terms baseline, preserving existing curation.
     * Exact kind/key lookups are performed within one JDBC transaction rather than a
     * batched INSERT...SELECT, so every inserted identity is traceable and deterministic.
     * Previously soft-deleted terms remain deleted; legacy phrase records are only
     * reactivated into the current scope when they occur in the Atomic worksheet.
     */
    public int importNew(List<GlossaryImportTerm> terms, GlossaryTermStatus status) throws SQLException {
        Objects.requireNonNull(terms, "terms");
        Objects.requireNonNull(status, "status");
        String lookupSql = "SELECT source, is_deleted FROM glossary_term WHERE kind=? AND term_key=?";
        String promoteSql = """
                UPDATE glossary_term SET source='ECOBANK_ATOMIC_XLSX', updated_at=CURRENT_TIMESTAMP
                WHERE kind=? AND term_key=? AND source='ECOBANK_XLSX' AND is_deleted=FALSE
                """;
        String insertSql = """
                INSERT INTO glossary_term (kind, term_key, english, persian, module, status, source)
                VALUES (?, ?, ?, ?, ?, ?, 'ECOBANK_ATOMIC_XLSX')
                """;
        try (Connection connection = dataSource.getConnection()) {
            connection.setAutoCommit(false);
            try (PreparedStatement lookup = connection.prepareStatement(lookupSql);
                 PreparedStatement promote = connection.prepareStatement(promoteSql);
                 PreparedStatement insert = connection.prepareStatement(insertSql)) {
                int created = 0;
                for (GlossaryImportTerm term : terms) {
                    Objects.requireNonNull(term, "import term");
                    // Detect a mismatched or stale normalized key before writing any data.
                    if (!term.key().equals(GlossaryNormalizer.key(term.english()))) {
                        throw new IllegalArgumentException("Inconsistent glossary key for " + term.english());
                    }
                    lookup.setString(1, term.kind().name());
                    lookup.setString(2, term.key());
                    boolean exists;
                    boolean deleted = false;
                    String existingSource = null;
                    try (ResultSet found = lookup.executeQuery()) {
                        exists = found.next();
                        if (exists) {
                            existingSource = found.getString(1);
                            deleted = found.getBoolean(2);
                        }
                    }
                    if (exists) {
                        if (!deleted && "ECOBANK_XLSX".equals(existingSource)) {
                            promote.setString(1, term.kind().name());
                            promote.setString(2, term.key());
                            promote.executeUpdate();
                        }
                    } else {
                        insert.setString(1, term.kind().name());
                        insert.setString(2, term.key());
                        insert.setString(3, term.english());
                        insert.setString(4, term.persian());
                        insert.setString(5, term.module());
                        insert.setString(6, status.name());
                        if (insert.executeUpdate() != 1) {
                            throw new SQLException("Glossary insert affected an unexpected number of rows: "
                                    + term.kind() + ":" + term.key());
                        }
                        created++;
                    }
                }
                connection.commit();
                return created;
            } catch (SQLException | RuntimeException exception) {
                connection.rollback();
                throw exception;
            }
        }
    }

    private static CanonicalInput requireInput(GlossaryTermRequest request) {
        Objects.requireNonNull(request, "Glossary request is required");
        if (request.kind() == null) throw new IllegalArgumentException("kind is required");
        String english = request.english() == null ? "" : request.english().strip();
        if (english.length() > 512) throw new IllegalArgumentException("English text exceeds 512 characters");
        String key = GlossaryNormalizer.key(english);
        if (request.kind() == GlossaryTermKind.ATOMIC && key.contains("_")) {
            throw new IllegalArgumentException("Atomic glossary entries must have exactly one component; use PHRASE");
        }
        GlossaryTermStatus status = request.status() == null ? GlossaryTermStatus.CANDIDATE : request.status();
        return new CanonicalInput(request.kind(), key, english,
                request.persian() == null ? "" : request.persian().strip(),
                request.module() == null ? "" : request.module().strip(), status);
    }

    private record CanonicalInput(GlossaryTermKind kind, String key, String english,
                                   String persian, String module, GlossaryTermStatus status) { }
}
