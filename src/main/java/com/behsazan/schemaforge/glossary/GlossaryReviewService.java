package com.behsazan.schemaforge.glossary;

import org.springframework.http.HttpStatus;
import org.springframework.jdbc.core.JdbcTemplate;
import org.springframework.jdbc.datasource.DataSourceTransactionManager;
import org.springframework.transaction.support.TransactionTemplate;
import org.springframework.web.server.ResponseStatusException;

import javax.sql.DataSource;
import java.security.MessageDigest;
import java.security.NoSuchAlgorithmException;
import java.util.HexFormat;
import java.util.List;
import java.util.Locale;
import java.util.Objects;

/** Administrator-mediated NEW report intake, review decisions, and immutable workflow history. */
public final class GlossaryReviewService {
    private final JdbcTemplate jdbc;
    private final TransactionTemplate tx;

    public GlossaryReviewService(DataSource dataSource) {
        Objects.requireNonNull(dataSource, "glossary dataSource");
        this.jdbc = new JdbcTemplate(dataSource);
        this.tx = new TransactionTemplate(new DataSourceTransactionManager(dataSource));
        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS glossary_review_occurrence (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    report_sha256 VARCHAR(64) NOT NULL,
                    report_row_index INT NOT NULL,
                    term_kind VARCHAR(12) NOT NULL,
                    term_key VARCHAR(256) NOT NULL,
                    source_name VARCHAR(1024) NOT NULL,
                    object_type VARCHAR(12) NOT NULL,
                    table_name VARCHAR(256) NOT NULL,
                    column_name VARCHAR(256) NOT NULL,
                    identifier VARCHAR(512) NOT NULL,
                    token_position INT NOT NULL,
                    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
                    CONSTRAINT uq_glossary_review_row UNIQUE (report_sha256, report_row_index)
                )
                """);
        jdbc.execute("CREATE INDEX IF NOT EXISTS ix_glossary_review_term "
                + "ON glossary_review_occurrence (term_kind, term_key)");
        jdbc.execute("""
                CREATE TABLE IF NOT EXISTS glossary_review_event (
                    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                    event_type VARCHAR(32) NOT NULL,
                    term_kind VARCHAR(12) NOT NULL,
                    term_key VARCHAR(256) NOT NULL,
                    status_before VARCHAR(12),
                    status_after VARCHAR(12),
                    reason VARCHAR(500) NOT NULL,
                    report_sha256 VARCHAR(64),
                    created_at TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
                )
                """);
        jdbc.execute("CREATE INDEX IF NOT EXISTS ix_glossary_review_event_term "
                + "ON glossary_review_event (term_kind, term_key, id)");
    }

    /** One report digest plus its row ordinal identifies each occurrence. Re-uploads do not duplicate it. */
    public ImportReportResult importReport(String filename, byte[] csv) {
        if (filename == null || !filename.toLowerCase(Locale.ROOT).endsWith(".csv")) {
            throw new IllegalArgumentException("Upload a glossary unknown-terms.csv report");
        }
        GlossaryReportCsvParser.ParsedReport parsed = GlossaryReportCsvParser.parse(csv);
        String digest = sha256(csv);
        return Objects.requireNonNull(tx.execute(ignored -> {
            int recorded = 0;
            int created = 0;
            int alreadyKnown = 0;
            for (GlossaryReportCsvParser.Occurrence occurrence : parsed.newOccurrences()) {
                Integer found = jdbc.queryForObject("SELECT COUNT(*) FROM glossary_review_occurrence "
                        + "WHERE report_sha256=? AND report_row_index=?", Integer.class,
                        digest, occurrence.rowNumber());
                if (found != null && found != 0) continue;
                jdbc.update("""
                        INSERT INTO glossary_review_occurrence
                        (report_sha256, report_row_index, term_kind, term_key, source_name, object_type,
                         table_name, column_name, identifier, token_position)
                        VALUES (?, ?, 'ATOMIC', ?, ?, ?, ?, ?, ?, ?)
                        """, digest, occurrence.rowNumber(), occurrence.term(), occurrence.source(),
                        occurrence.objectType(), occurrence.tableName(), occurrence.columnName(),
                        occurrence.identifier(), occurrence.position());
                recorded++;
                Integer known = jdbc.queryForObject("SELECT COUNT(*) FROM glossary_term "
                        + "WHERE kind='ATOMIC' AND term_key=?", Integer.class, occurrence.term());
                if (known != null && known != 0) {
                    alreadyKnown++;
                } else {
                    // Do not resurrect soft-deleted terms or overwrite approved/rejected curation.
                    jdbc.update("""
                            INSERT INTO glossary_term (kind, term_key, english, persian, module, status, source)
                            VALUES ('ATOMIC', ?, ?, '', '', 'CANDIDATE', 'DISCOVERY_REPORT')
                            """, occurrence.term(), occurrence.term());
                    audit("DISCOVERED", GlossaryTermKind.ATOMIC, occurrence.term(), null, "CANDIDATE",
                            "First NEW occurrence in reviewed report", digest);
                    created++;
                }
            }
            return new ImportReportResult(digest, parsed.sourceRows(), parsed.newOccurrences().size(),
                    recorded, parsed.newOccurrences().size() - recorded, parsed.skippedNonNew(), created,
                    alreadyKnown);
        }));
    }

    /** Only a live CANDIDATE (baseline, manual or discovered) can be decided and audited. */
    public DecisionResult decide(DecisionRequest request) {
        Objects.requireNonNull(request, "decision is required");
        String key = GlossaryNormalizer.key(request.term());
        GlossaryTermKind kind = request.kind() != null ? request.kind()
                : key.contains("_") ? GlossaryTermKind.PHRASE : GlossaryTermKind.ATOMIC;
        if (kind == GlossaryTermKind.ATOMIC && key.contains("_")) {
            throw new IllegalArgumentException("Multi-component terms must be reviewed as PHRASE");
        }
        if (request.to() != GlossaryTermStatus.APPROVED && request.to() != GlossaryTermStatus.REJECTED) {
            throw new IllegalArgumentException("Review decision must be APPROVED or REJECTED");
        }
        String reason = boundedText(request.reason(), 500, true, "reason");
        String persian = boundedText(request.persian(), 2000, false, "persian");
        String module = boundedText(request.module(), 1000, false, "module");
        return Objects.requireNonNull(tx.execute(ignored -> {
            // Baseline, manual, and discovered candidates all require explicit review.
            // Evidence is mandatory for report-created candidates, but curated baseline
            // terms already have authoritative provenance in glossary_term.source.
            List<CurrentTerm> terms = jdbc.query("""
                    SELECT id, status, persian, module, is_deleted FROM glossary_term
                    WHERE kind=? AND term_key=? FOR UPDATE
                    """, (rs, rowNum) -> new CurrentTerm(rs.getLong(1), rs.getString(2),
                    rs.getString(3), rs.getString(4), rs.getBoolean(5)), kind.name(), key);
            if (terms.isEmpty()) {
                throw new ResponseStatusException(HttpStatus.NOT_FOUND, "Glossary term does not exist");
            }
            CurrentTerm term = terms.getFirst();
            if (term.deleted() || !"CANDIDATE".equals(term.status())) {
                throw new ResponseStatusException(HttpStatus.CONFLICT,
                        "Only active CANDIDATE terms can be reviewed");
            }
            String newPersian = persian.isEmpty() ? term.persian() : persian;
            String newModule = module.isEmpty() ? term.module() : module;
            int updated = jdbc.update("""
                    UPDATE glossary_term SET status=?, persian=?, module=?, updated_at=CURRENT_TIMESTAMP
                    WHERE id=? AND status='CANDIDATE' AND is_deleted=FALSE
                    """, request.to().name(), newPersian, newModule, term.id());
            if (updated != 1) {
                throw new ResponseStatusException(HttpStatus.CONFLICT, "Review status changed concurrently");
            }
            audit("REVIEW_DECISION", kind, key, "CANDIDATE", request.to().name(), reason, null);
            return new DecisionResult(term.id(), kind, key, request.to(), reason);
        }));
    }

    /** Baseline and discovered candidates share one pending queue; optionally include resolved history. */
    public QueuePage queue(boolean includeResolved, int page, int size) {
        validatePage(page, size);
        List<QueueItem> all = jdbc.query("""
                SELECT t.kind AS term_kind, t.term_key,
                       COALESCE(o.occurrence_count, 0) AS occurrence_count,
                       COALESCE(o.sample_source, t.source) AS sample_source,
                       COALESCE(o.first_seen, t.created_at) AS first_seen,
                       COALESCE(o.last_seen, t.updated_at) AS last_seen,
                       t.id AS term_id, t.status AS term_status, t.is_deleted
                FROM glossary_term t
                LEFT JOIN (
                    SELECT term_kind, term_key, COUNT(*) AS occurrence_count,
                           MIN(source_name) AS sample_source,
                           MIN(created_at) AS first_seen,
                           MAX(created_at) AS last_seen
                    FROM glossary_review_occurrence
                    GROUP BY term_kind, term_key
                ) o ON o.term_kind=t.kind AND o.term_key=t.term_key
                WHERE (t.status='CANDIDATE' OR o.occurrence_count IS NOT NULL
                       OR EXISTS (SELECT 1 FROM glossary_review_event e
                                  WHERE e.term_kind=t.kind AND e.term_key=t.term_key))
                  AND (t.kind='ATOMIC' OR t.source<>'ECOBANK_XLSX')
                ORDER BY t.term_key ASC
                """, (rs, row) -> new QueueItem(rs.getString("term_kind"), rs.getString("term_key"),
                rs.getLong("occurrence_count"), rs.getString("sample_source"),
                rs.getString("first_seen"), rs.getString("last_seen"),
                rs.getLong("term_id"),
                rs.getBoolean("is_deleted") ? "DELETED" : rs.getString("term_status")));
        List<QueueItem> filtered = includeResolved ? all : all.stream()
                .filter(item -> "CANDIDATE".equals(item.status())).toList();
        int offset = page * size;
        return new QueuePage(offset >= filtered.size() ? List.of()
                : List.copyOf(filtered.subList(offset, Math.min(filtered.size(), offset + size))),
                page, size, filtered.size());
    }

    /** Append-only API history for discovery and reviewed candidate decisions, never storing the admin key. */
    public HistoryPage history(String term, int page, int size) {
        validatePage(page, size);
        String key = term == null || term.isBlank() ? null : GlossaryNormalizer.key(term);
        List<HistoryEvent> events = jdbc.query("""
                SELECT id, event_type, term_kind, term_key, status_before, status_after, reason,
                       report_sha256, created_at
                FROM glossary_review_event ORDER BY id DESC
                """, (rs, row) -> new HistoryEvent(rs.getLong("id"), rs.getString("event_type"),
                rs.getString("term_kind"), rs.getString("term_key"),
                rs.getString("status_before"), rs.getString("status_after"),
                rs.getString("reason"), rs.getString("report_sha256"), rs.getString("created_at")));
        List<HistoryEvent> filtered = key == null ? events : events.stream()
                .filter(event -> key.equals(event.termKey())).toList();
        int offset = page * size;
        return new HistoryPage(offset >= filtered.size() ? List.of()
                : List.copyOf(filtered.subList(offset, Math.min(filtered.size(), offset + size))),
                page, size, filtered.size());
    }

    private void audit(String event, GlossaryTermKind kind, String key,
                       String before, String after, String reason, String digest) {
        jdbc.update("""
                INSERT INTO glossary_review_event
                (event_type, term_kind, term_key, status_before, status_after, reason, report_sha256)
                VALUES (?, ?, ?, ?, ?, ?, ?)
                """, event, kind.name(), key, before, after, reason, digest);
    }

    private static String boundedText(String value, int max, boolean required, String field) {
        String result = value == null ? "" : value.strip();
        if (result.length() > max || (required && result.isEmpty())) {
            throw new IllegalArgumentException("Invalid " + field + " (required=" + required
                    + ", max=" + max + ")");
        }
        return result;
    }

    private static void validatePage(int page, int size) {
        if (page < 0 || size < 1 || size > 100 || page > Integer.MAX_VALUE / size) {
            throw new IllegalArgumentException("page must be >= 0 and size must be between 1 and 100");
        }
    }

    private static String sha256(byte[] bytes) {
        try {
            return HexFormat.of().formatHex(MessageDigest.getInstance("SHA-256").digest(bytes));
        } catch (NoSuchAlgorithmException exception) {
            throw new IllegalStateException("SHA-256 is unavailable", exception);
        }
    }

    private record CurrentTerm(long id, String status, String persian, String module, boolean deleted) { }
    public record ImportReportResult(String reportSha256, int sourceRows, int newOccurrences,
                                     int recordedOccurrences, int previouslyRecorded,
                                     int skippedNonNew, int createdCandidates, int alreadyKnownOccurrences) { }
    public record DecisionRequest(String term, GlossaryTermStatus to, String persian,
                                  String module, String reason, GlossaryTermKind kind) {
        public DecisionRequest(String term, GlossaryTermStatus to, String persian,
                               String module, String reason) {
            this(term, to, persian, module, reason, null);
        }
    }
    public record DecisionResult(long id, GlossaryTermKind kind, String key,
                                 GlossaryTermStatus status, String reason) { }
    public record QueueItem(String kind, String key, long occurrences, String sampleSource,
                            String firstSeen, String lastSeen, Long id, String status) { }
    public record QueuePage(List<QueueItem> items, int page, int size, long total) { }
    public record HistoryEvent(long id, String eventType, String kind, String termKey,
                               String statusBefore, String statusAfter, String reason,
                               String reportSha256, String createdAt) { }
    public record HistoryPage(List<HistoryEvent> items, int page, int size, long total) { }
}
