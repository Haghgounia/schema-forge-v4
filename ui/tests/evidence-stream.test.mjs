import assert from 'node:assert/strict';
import { EventEmitter } from 'node:events';
import { test } from 'node:test';
import { TermEvidenceStreamReader, MAX_EVIDENCE_SCAN_BYTES } from '../src/evidenceStream.ts';
import { readTermEvidence } from '../src/zipReports.ts';

const header = '"source_name","object_type","table_name","column_name","identifier","unknown_term","token_position","review_status"\r\n';
const row = (term, name = 'VISA_NUMBER', source = 'e.xml') =>
  `"${source}","COLUMN","CUSTOMERS","${name}","${name}","${term}","1","NEW"\r\n`;

/** JSZip's internalStream is event-based and receives decompressed chunks. */
function fakeInspection(bytes, chunkSize = 16_384) {
  const chunkArray = new Uint8Array(bytes);
  const fakeEntry = {
    internalStream() {
      const emitter = new EventEmitter();
      let paused = false, offset = 0, started = false;
      const pump = () => {
        if (paused) return;
        if (offset < chunkArray.byteLength) {
          const end = Math.min(offset + chunkSize, chunkArray.byteLength);
          emitter.emit('data', chunkArray.subarray(offset, end));
          offset = end;
          setImmediate(pump);
        } else emitter.emit('end');
      };
      emitter.pause = () => { paused = true; };
      emitter.resume = () => { if (!started) { started = true; setImmediate(pump); } };
      return emitter;
    },
  };
  return {archive: {file: name => name === 'reports/glossary/unknown-terms.csv' ? fakeEntry : null}};
}

test('RFC-4180 streaming handles BOM, UTF-8 chunk splits, quotes, multiline fields and CRLF boundaries', () => {
  const csv = '\ufeff' + header + row('VISA', 'VISA_NUMBER', 'پوشه/نمونه""bank.csv') +
    '"a,b\nnew","COLUMN","CUST","VISA_TYPE","VISA_TYPE","VISA","1","NEW"\r\n' +
    row('VISA_EXTRA') + row('visa', 'VISA_DATE');
  const bytes = new TextEncoder().encode(csv);
  const parser = new TermEvidenceStreamReader('VISA');
  for (const byte of bytes) parser.writeBytes(new Uint8Array([byte]));
  const result = parser.finish();
  assert.equal(result.total, 3);
  assert.deepEqual(result.rows.map(item => item.column), ['VISA_NUMBER','VISA_TYPE','VISA_DATE']);
  assert.equal(result.rows[1].source, 'a,b\nnew');
});

test('a CSV larger than previous 2 MiB bound is fully scanned, counting all matches while keeping only 25 rows', async () => {
  const count = 84_000;
  const text = header + Array.from({length:count}, (_, i) => row(i % 4 === 0 ? 'ACC' : 'OTHER', `FIELD_${i}`)).join('');
  const bytes = new TextEncoder().encode(text);
  assert.ok(bytes.length > 5 * 1024 * 1024, `generated bytes ${bytes.length}`);
  const evidence = await readTermEvidence(fakeInspection(bytes, 4097), 'ACC');
  assert.equal(evidence.total, count / 4);
  assert.equal(evidence.rows.length, 25);
  assert.equal(evidence.rows[0].column,'FIELD_0');
  assert.equal(evidence.rows[24].column,'FIELD_96');
});

test('missing evidence CSV yields null, not a misleading zero-count success', async () => {
  assert.equal(await readTermEvidence({archive: {file: () => null}}, 'ACC'), null);
});

test('invalid CSV header and malformed quotes fail closed', async () => {
  const invalidHeader = new TextEncoder().encode('"SOURCE","NOT_TERM"\r\n"doc","ACC"\r\n');
  await assert.rejects(readTermEvidence(fakeInspection(invalidHeader), 'ACC'), /unknown_term/);
  const invalidQuote = new TextEncoder().encode(header + '"abc,COLUMN,CUST,FIELD,FIELD,ACC,1,NEW\n');
  await assert.rejects(readTermEvidence(fakeInspection(invalidQuote), 'ACC'), /نقل‌قول/);
});

