test('scanner respects a decompressed-byte bound independently of 500 MiB server uploads', () => {
  assert.equal(MAX_EVIDENCE_SCAN_BYTES, 128 * 1024 * 1024);
});

test('a CSV containing no matching occurrences returns an exact zero', async () => {
  const value = await readTermEvidence(fakeInspection(new TextEncoder().encode(header + row('OTHER'))), 'ACC');
  assert.deepEqual(value, {total:0,rows:[]});
});


test('oversized decompressed evidence is refused before holding or parsing it', async () => {
  const entry = {internalStream() {
    const emitter = new EventEmitter();
    emitter.pause = () => {};
    emitter.resume = () => setImmediate(() => emitter.emit('data', {byteLength: MAX_EVIDENCE_SCAN_BYTES + 1}));
    return emitter;
  }};
  const inspection = {archive: {file: () => entry}};
  await assert.rejects(readTermEvidence(inspection, 'ACC'), /۱۲۸/);
});
